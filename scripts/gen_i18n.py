#!/usr/bin/env python3
"""English UI text for the badge (see firmware/passport_suite/main/i18n.hpp).

  gen_i18n.py           check i18n/en.json and write main/i18n_en.hpp
  gen_i18n.py --todo    also write i18n/todo.json: Chinese text in the UI sources that en.json lacks, with where it is

The phone setup page (wifi_portal_page.hpp) gets i18n/portal-en.json as its EN table; "{}" there matches any text.

en.json maps Chinese to English ({"所在城市：%s": "City: %s"}); "" means "leave it Chinese" (voice keywords, data).
"""
import json
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
SUITE = REPO / 'firmware/passport_suite'
EN = SUITE / 'i18n/en.json'
SPEC = re.compile(r'%(?:[1-9]\$)?[-+ 0#]*\d*(?:\.\d+)?(?:hh|h|ll|l|z)?[sdufxXc]')
CJK = re.compile(r'[㐀-鿿＀-￯　-〿]')
# Sources whose Chinese text can reach the screen. Content tables (stations, cities, words, 黄历, fonts) stay Chinese.
UI = ['firmware/passport_suite/main/' + n for n in (
    'apps.hpp', 'key_hints.hpp', 'ui.cpp', 'home_ui.cpp', 'suite.cpp', 'suite.hpp', 'settings.cpp', 'menu_layout.hpp', 'domain.cpp',
    'health.hpp', 'ledger.hpp', 'macro.hpp', 'macro_json.hpp', 'train.hpp', 'weather.hpp', 'score.hpp', 'typhoon.hpp',
    'todo_time.hpp', 'calc.hpp', 'voice_add.hpp', 'moon.hpp', 'city_location.hpp')] + [
    'firmware/passport_device/main/' + n for n in ('native_services.cpp', 'macro_services.cpp', 'tool_tasks.cpp', 'board.cpp')] + [
    'firmware/passport_connectivity/main/' + n for n in ('live_services.cpp', 'main.cpp', 'menu_service.cpp')]
LITERAL = re.compile(r'"((?:[^"\\\n]|\\.)*)"')


def specs(text):
    """The conversions in order, '%2$s' counted as the second; '%%' skipped."""
    found, n = [], 0
    for m in SPEC.finditer(text.replace('%%', '')):
        s = m.group(0); pos = re.match(r'%([1-9])\$', s)
        index = int(pos.group(1)) - 1 if pos else n
        n += not pos
        found.append((index, 'n' if s[-1] not in 'sc' else 's'))
    return sorted(found)


def check(table):
    problems = []
    for zh, en in table.items():
        if not en: continue
        if CJK.search(en): problems.append(f'Chinese left in English: {zh!r} -> {en!r}')
        if SPEC.search(zh) and specs(zh) != specs(en):
            problems.append(f'printf pieces differ: {zh!r} -> {en!r}')
    return problems


def unescape(s):
    return re.sub(r'\\(.)', lambda m: {'n': '\n', 't': '\t', '"': '"', '\\': '\\'}.get(m.group(1), '\\' + m.group(1)), s)


def todo(table):
    seen = {}
    for name in UI:
        path = REPO / name
        if not path.exists(): continue
        for number, line in enumerate(path.read_text(encoding='utf-8').splitlines(), 1):
            if line.lstrip().startswith('//'): continue
            for m in LITERAL.finditer(line):
                text = unescape(m.group(1))
                if not CJK.search(text) or text in table or text in seen: continue
                seen[text] = {'where': f'{path.name}:{number}', 'code': line.strip()[:200]}
    (SUITE / 'i18n/todo.json').write_text(json.dumps(seen, ensure_ascii=False, indent=1) + '\n', encoding='utf-8')
    print(f'{len(seen)} untranslated texts -> i18n/todo.json')



# The assistant page's translator (the phone page carries the same code inline): PassportI18n.start(true) translates
# the page and whatever is added to it later.
JS = '''// Generated by scripts/gen_i18n.py. Do not edit.
(()=>{const EN=/*EN*/;
const CJK=/[\\u3400-\\u9fff\\u3000-\\u303f\\uff00-\\uffef]/,PATTERNS=Object.keys(EN).filter(k=>k.includes('{}')).sort((a,b)=>b.replace(/\\{\\}/g,'').length-a.replace(/\\{\\}/g,'').length).map(k=>[new RegExp('^'+k.split('{}').map(s=>s.replace(/[.*+?^$()|[\\]\\\\]/g,'\\\\$&')).join('(.*?)')+'$','s'),EN[k]]);
let english=false;
function one(s){if(EN[s])return EN[s];for(const [re,en] of PATTERNS){const m=s.match(re);if(m){let i=1;return en.replace(/\\{\\}/g,()=>{const p=m[i++];return EN[p]||p;});}}return null;}
function tx(s){if(!english||!s||!CJK.test(s))return s;const core=s.trim(),lead=s.slice(0,s.indexOf(core)),trail=s.slice(lead.length+core.length);let r=one(core);
 if(r==null&&core.includes(' · ')){const parts=core.split(' · ').map(p=>one(p.trim()));if(parts.some(p=>p!=null))r=core.split(' · ').map((p,i)=>parts[i]??p).join(' · ');}return r==null?s:lead+r+trail;}
const ATTRS=['placeholder','aria-label','title','label'];
function attrs(e){for(const a of ATTRS){const v=e.getAttribute&&e.getAttribute(a);if(v){const t=tx(v);if(t!==v)e.setAttribute(a,t);}}}
function localize(root){if(root.nodeType===3){const t=tx(root.nodeValue);if(t!==root.nodeValue)root.nodeValue=t;return;}if(root.nodeType!==1)return;attrs(root);
 const w=document.createTreeWalker(root,NodeFilter.SHOW_TEXT);for(let n;(n=w.nextNode());){const t=tx(n.nodeValue);if(t!==n.nodeValue)n.nodeValue=t;}for(const e of root.querySelectorAll('[placeholder],[aria-label],[title],optgroup'))attrs(e);}
window.PassportI18n={tx,get english(){return english},start(on){if(english||!on)return;english=true;document.documentElement.lang='en';document.title=tx(document.title);localize(document.body);
 new MutationObserver(list=>{for(const m of list){if(m.type==='characterData')localize(m.target);else if(m.type==='attributes')attrs(m.target);else m.addedNodes.forEach(localize);}}).observe(document.body,{subtree:true,childList:true,characterData:true,attributes:true,attributeFilter:ATTRS});}};})();
'''


def main():
    table = json.loads(EN.read_text(encoding='utf-8'))
    problems = check(table)
    for p in problems: print(p, file=sys.stderr)
    if problems: sys.exit(1)
    rows = sorted(((zh, en) for zh, en in table.items() if en), key=lambda kv: kv[0].encode())
    c = lambda s: json.dumps(s, ensure_ascii=False)  # a JSON string is a valid C string literal here
    # Formats with Chinese in their fixed text, most fixed text first (the more specific match wins).
    formats = sorted((i for i, (zh, _) in enumerate(rows) if SPEC.search(zh.replace('%%', '')) and CJK.search(SPEC.sub('', zh))),
                     key=lambda i: -len(SPEC.sub('', rows[i][0]).encode()))
    (SUITE / 'main/i18n_en.hpp').write_text(
        '// Generated by scripts/gen_i18n.py from i18n/en.json. Do not edit.\n#pragma once\n#include <array>\n#include <cstdint>\n'
        'namespace passport {\ninline constexpr Translation kEnglish[]{\n'
        + ''.join(f'    {{{c(zh)}, {c(en)}}},\n' for zh, en in rows)
        + f'}};\n// kEnglish entries that are printf formats, tried in this order.\ninline constexpr std::array<uint16_t,{len(formats)}> kEnglishFormats{{'
        + ','.join(map(str, formats)) + '};\n}\n', encoding='utf-8')
    print(f'{len(rows)} translations, {len(formats)} formats')
    portal = json.loads((SUITE / 'i18n/portal-en.json').read_text(encoding='utf-8'))
    bad = [k for k, v in portal.items() if not v or CJK.search(v) or k.count('{}') != v.count('{}')]
    if bad: sys.exit(f'portal-en.json: empty, Chinese or unmatched {{}}: {bad}')
    page_path = REPO / 'firmware/passport_device/main/wifi_portal_page.hpp'
    page = page_path.read_text(encoding='utf-8')
    begin, end = page.index('// I18N_BEGIN\n') + len('// I18N_BEGIN\n'), page.index('// I18N_END')
    portal_js = json.dumps(dict(sorted(portal.items())), ensure_ascii=False, separators=(',', ':'))
    assert ')PORTAL' not in portal_js
    new = page[:begin] + f'const EN={portal_js};\n' + page[end:]
    if new != page: page_path.write_text(new, encoding='utf-8')
    print(f'{len(portal)} phone page texts')
    # The PC Assistant: its own texts over the phone page's (the menu editor is shared), for Python and its web page.
    assistant = {**portal, **json.loads((SUITE / 'i18n/assistant-en.json').read_text(encoding='utf-8'))}
    bad = [k for k, v in assistant.items() if not v or CJK.search(v) or k.count('{}') != v.count('{}')]
    if bad: sys.exit(f'assistant-en.json: empty, Chinese or unmatched {{}}: {bad}')
    (REPO / 'scripts/passport_i18n.json').write_text(json.dumps(dict(sorted(assistant.items())), ensure_ascii=False, indent=0) + '\n', encoding='utf-8')
    (REPO / 'scripts/passport_i18n.js').write_text(JS.replace('/*EN*/', json.dumps(dict(sorted(assistant.items())), ensure_ascii=False, separators=(',', ':'))), encoding='utf-8')
    print(f'{len(assistant)} assistant texts')
    if '--todo' in sys.argv: todo(table)


if __name__ == '__main__':
    main()
