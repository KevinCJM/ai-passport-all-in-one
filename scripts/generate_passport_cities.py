#!/usr/bin/env python3
"""Generate the shared offline city catalog for voice and the phone portal."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def outputs():
    data = json.loads((ROOT / 'data/international-cities.json').read_text())
    quote = lambda value: json.dumps(value, ensure_ascii=False)
    entries, countries, groups = [], [], {}
    for country in data['countries']:
        code, name = country['code'], country['name']
        countries.append('    {%s,%s,%s},' % (quote(code), quote(name), quote('|'.join(country['aliases']))))
        group = groups.setdefault(country['group'], [])
        for city in country['cities']:
            lat, lon = city['latitude'], city['longitude']
            aliases = '|'.join(city['aliases'])
            entries.append('    {%s,%s,%.5ff,%.5ff,%s,%s},' %
                           (quote(city['name']), quote(name), lat, lon, quote(code), quote(aliases)))
            group.append([city['name'], lat, lon, name, code, aliases + '|' + '|'.join(country['aliases'])])
    notice = '// Generated by scripts/generate_passport_cities.py; GeoNames, CC BY 4.0.\n'
    portal = ROOT / 'firmware/passport_device/main/wifi_portal_page.hpp'
    text = portal.read_text()
    begin, end = '// INTERNATIONAL_CITIES_BEGIN', '// INTERNATIONAL_CITIES_END'
    block = begin + '\nCITIES.push(...' + json.dumps([[name, '', cities] for name, cities in groups.items()],
                                                    ensure_ascii=False, separators=(',', ':')) + ');\n' + end
    if begin in text:
        start, finish = text.index(begin), text.index(end) + len(end)
        text = text[:start] + block + text[finish:]
    else:
        anchor = 'const CURRENCIES='
        text = text.replace(anchor, block + '\n' + anchor, 1)
    return {
        ROOT / 'firmware/passport_suite/main/international_city_entries.inc': notice + '\n'.join(entries) + '\n',
        ROOT / 'firmware/passport_suite/main/city_countries.inc': notice + '\n'.join(countries) + '\n',
        portal: text,
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    stale = []
    for path, content in outputs().items():
        if not path.exists() or path.read_text() != content:
            stale.append(str(path.relative_to(ROOT)))
            if not args.check:
                path.write_text(content)
    if args.check and stale:
        parser.error('regenerate city catalog: ' + ', '.join(stale))
    print('CITY_CATALOG_OK')


if __name__ == '__main__':
    main()
