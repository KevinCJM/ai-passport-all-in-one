#!/usr/bin/env python3
"""Create an OFL bitmap subset for the actual firmware text, using bundled Pillow."""
import hashlib
import json
import re
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont
from font_rle import compress

ROOT = Path(__file__).resolve().parents[1]
PROJECT = ROOT / 'firmware/passport_suite'
DONOR = ROOT / 'deps/lvgl__lvgl/scripts/built_in_font'
SOURCE = DONOR / 'SourceHanSansSC-Normal.otf'
# Source Han Sans has no IPA; the word list's phonetic symbols come from DejaVu Sans.
FALLBACK = DONOR / 'DejaVuSans.ttf'
AWESOME = DONOR / 'FontAwesome5-Solid+Brands+Regular.woff'


def write_if_changed(path: Path, text: str) -> None:
    if not path.exists() or path.read_text() != text:
        path.write_text(text)


def glyphs(codes, size):
    """4 bpp bitmaps and LVGL glyph descriptors for the code points, at size px."""
    primary, fallback = ImageFont.truetype(str(SOURCE), size), ImageFont.truetype(str(FALLBACK), size)
    shape = lambda f, c: (f.getbbox(c), bytes(f.getmask(c)))
    notdef = shape(primary, chr(0xE000))
    bitmaps, descriptors = [], ['{0, 0, 0, 0, 0, 0}']
    for code in codes:
        char = chr(code)
        font = fallback if code > 126 and shape(primary, char) == notdef else primary
        x0, y0, x1, y1 = font.getbbox(char, anchor='ls')
        width, height = x1 - x0, y1 - y0
        canvas = Image.new('L', (max(width, 1), max(height, 1)))
        ImageDraw.Draw(canvas).text((-x0, -y0), char, font=font, fill=255, anchor='ls')
        values = [p >> 4 for p in canvas.getdata()] if width and height else []
        descriptors.append('{%d, %d, %d, %d, %d, %d}' %
            (len(bitmaps), round(font.getlength(char) * 16), width, height, x0, -y1))
        # LVGL RLE with line prefilter (bitmap_format 1): lossless, about a quarter smaller.
        if values: bitmaps.extend(compress(values, width, height, 4, True))
    return bitmaps + [0], descriptors  # The decoder may read one byte past the last glyph.


